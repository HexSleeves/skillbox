export type SkillIcon =
  | { kind: "icon"; name: string; background: string }
  | { kind: "emoji"; value: string }
  | { kind: "image"; src: string };
export function parseSkillIcon(value: unknown): SkillIcon | null {
  if (value == null) return null;
  if (typeof value !== "object") return null; // Legacy frontmatter icons remain supported by their original consumers.
  const i = value as Record<string, unknown>;
  if (
    i.kind === "icon" &&
    typeof i.name === "string" &&
    Object.hasOwn(ICON_PACK, i.name) &&
    typeof i.background === "string" &&
    /^#[0-9a-f]{6}$/i.test(i.background)
  )
    return { kind: "icon", name: i.name, background: i.background };
  if (
    i.kind === "emoji" &&
    typeof i.value === "string" &&
    i.value.length <= 32 &&
    /\p{Extended_Pictographic}|\p{Regional_Indicator}/u.test(i.value)
  )
    return { kind: "emoji", value: i.value };
  if (
    i.kind === "image" &&
    typeof i.src === "string" &&
    i.src.length <= 32000 &&
    /^data:image\/(png|webp|jpeg);base64,[A-Za-z0-9+/]+=*$/.test(i.src)
  )
    return { kind: "image", src: i.src };
  throw new Error("Choose an icon, emoji, or PNG/JPEG/WebP image under 24 KB");
}
export function skillIconUrl(icon?: SkillIcon | null): string | undefined {
  if (!icon) return;
  if (icon.kind === "image") return icon.src;
  const body =
    icon.kind === "emoji"
      ? `<text x="12" y="19" text-anchor="middle" font-size="20">${icon.value.replace(/[<>&]/g, "")}</text>`
      : `<rect width="24" height="24" rx="5" fill="${icon.background}"/><g transform="translate(4 4) scale(.6667)" fill="none" stroke="white" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${(
          ICON_PACK[icon.name as keyof typeof ICON_PACK] ??
          ICON_PACK["book-open"]
        )
          .map(
            ([tag, attrs]) =>
              `<${tag} ${Object.entries(attrs)
                .filter(([k]) => k !== "key")
                .map(([k, v]) => `${k}="${v}"`)
                .join(" ")}/>`,
          )
          .join("")}</g>`;
  return `data:image/svg+xml,${encodeURIComponent(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">${body}</svg>`)}`;
}
